// Sélecteur de couleur AU DOIGT, tablette 820 × 1180 tactile : cibles ≥ 36 px, curseurs glissés au doigt.
import { banc, rgb } from './commun.mjs';
const b = await banc(1440, 900);
b.ok(await b.ouvrir('Physiologie rénale (jumelle)'), 'cours ouvert (1 440 px)');
await b.c.send('Emulation.setDeviceMetricsOverride', { width: 820, height: 1180, deviceScaleFactor: 2, mobile: true });
await b.c.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 });
await b.c.send('Emulation.setEmitTouchEventsForMouse', { enabled: true, configuration: 'mobile' });
await b.dormir(1500);
b.ok(await b.ev(`matchMedia('(pointer: coarse)').matches`), 'pointeur « coarse » (doigt)');
const bx = `[...document.querySelectorAll('.note-box')].find(n=>n.innerText.includes('Boîte outil'))`;
await b.ev(`(()=>{const e=${bx};e.scrollIntoView({block:'center'});return 1})()`); await b.dormir(800);
await b.tape(await b.pos(bx, false));
await b.tape(await b.pos(`document.querySelector('.nb-actions .sc-bouton')`, false));
const cible = await b.rect(`document.querySelector('.nb-actions .sc-bouton')`);
b.ok(cible && cible.w >= 36 && cible.h >= 36, 'bouton couleur de la boîte ≥ 36 px au doigt', cible && `${cible.w}×${cible.h}`);
await b.tape(await b.pos(`document.querySelector('.sc-pop .sc-roue-btn')`, false));
b.ok(await b.ev(`!!document.querySelector('.sc-fenetre')`), 'panneau « Personnalisée » ouvert au doigt');
b.ok(!(await b.ev(`document.activeElement && document.activeElement.classList.contains('sc-hex')`)), 'au doigt, le champ hex ne prend PAS le focus (pas de clavier qui surgit)');
const teinte = await b.rect(`document.querySelector('.sc-teinte')`), carre = await b.rect(`document.querySelector('.sc-carre')`);
b.ok(teinte.h >= 36 && carre.h >= 36, 'zones de prise ≥ 36 px', `teinte ${teinte.w}×${teinte.h}, carré ${carre.w}×${carre.h}`);
const fen = await b.rect(`document.querySelector('.sc-fenetre')`);
b.ok(fen.y >= 0 && fen.b <= 1180 && fen.x >= 0 && fen.r <= 820, 'panneau dans l’écran', JSON.stringify(fen));
const h0 = await b.ev(`document.querySelector('.sc-teinte').getAttribute('aria-valuenow')`);
await b.doigt([teinte.x + teinte.w * 0.1, teinte.cy], [teinte.x + teinte.w * 0.33, teinte.cy]);
const h1 = await b.ev(`document.querySelector('.sc-teinte').getAttribute('aria-valuenow')`);
b.ok(Math.abs(h1 - 119) < 6, 'teinte glissée AU DOIGT', `${h0}° → ${h1}°`);
await b.doigt([carre.x + carre.w * 0.3, carre.y + carre.h * 0.3], [carre.x + carre.w * 0.95, carre.y + carre.h * 0.4]);
const hex = await b.ev(`'#'+document.querySelector('.sc-hex').value`);
b.ok((await b.fond(bx)).includes(rgb(hex)), 'aperçu en direct sur la boîte', hex);
await b.capt('doigt-tablette');
await b.tape(await b.pos(`[...document.querySelectorAll('.sc-fenetre button')].find(x=>x.innerText.includes('OK'))`, false));
await b.dormir(400);
const enr = await b.S(`return (await S.getAll('annotations')).find(a=>a.ficheId==='f-fj'&&JSON.stringify(a.content||'').includes('Boîte outil')).couleur`);
b.ok(enr === hex, 'OK au doigt : couleur enregistrée', enr);
b.ok(!b.erreurs.length, '0 erreur JS', b.erreurs.join(' | '));
await b.c.send('Emulation.setTouchEmulationEnabled', { enabled: false });
await b.c.send('Emulation.setEmitTouchEventsForMouse', { enabled: false });
b.c.fermer();
