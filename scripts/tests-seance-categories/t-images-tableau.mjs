// (24/10) Image collée sur le TABLEAU d'un cours (copie des vraies données, profil isolé 9341 : CDP_PORT=9341).
// Même composant de rognage et même règle de redimension que le lecteur et les documents.
import { banc } from '../tests-pdfreader-v3/commun.mjs';
import { outilsImages } from './commun-images.mjs';
const b = await banc(1440, 900);
const o = outilsImages(b);
b.ok(await b.ouvrir('Introduction 26 27', { recharger: true }), 'cours ouvert');
await b.dormir(1200);
await b.clic(await b.pos(`[...document.querySelectorAll('button')].find((x) => x.innerText.trim() === 'Tableau')`, false), { att: 1500 });
b.ok(await b.ev(`!!document.querySelector('.tb2')`), 'tableau du cours affiché');
const board = () => b.S(`const id = (await S.getAll('board')).map((x) => x.id).find((x) => x.includes('fmv967iu0nq14')); return id ? await S.getOne('board', id) : null;`);
const avant = new Set(((await board()) || { objects: [] }).objects.map((x) => x.id));
await b.ev(`(document.querySelector('.tb2').focus(), 1)`);
await o.collerImage(`document.querySelector('.tb2')`);
await b.dormir(1500);
let bd = await board();
const img = bd && bd.objects.find((x) => x.type === 'image' && !avant.has(x.id));
b.ok(!!img, 'image collée sur le tableau', img && `${img.w}×${img.h}`);
const sel = `document.querySelector('.tb2-image[data-objet="${img.id}"]')`;
const objet = async () => (await board()).objects.find((x) => x.id === img.id);
let r = await o.rect(sel);
await b.clic([r.x + r.w / 2, r.y + r.h / 2], { att: 500 });
const a0 = await objet();
await o.glisser(await o.coin(sel, 'se'), 80, 10);
const a1 = await objet();
b.ok(a1.w > a0.w && Math.abs(a1.h / a1.w - a0.h / a0.w) < 0.02 && a1.x === a0.x && a1.y === a0.y, 'coin bas-droit → agrandie, proportions conservées', `${a0.w}×${a0.h} → ${a1.w}×${a1.h}`);
await o.glisser(await o.coin(sel, 'nw'), 40, -30, { maj: true });
const a2 = await objet();
b.ok(Math.abs(a2.h / a2.w - a1.h / a1.w) > 0.03 && a2.x + a2.w === a1.x + a1.w, 'coin haut-gauche avec Maj → libre');
for (const c of ['ne', 'sw']) { const av = await objet(); await o.glisser(await o.coin(sel, c), c === 'ne' ? 20 : -20, c === 'ne' ? -10 : 10); b.ok((await objet()).w > av.w, `coin ${c} → redimension`); }
await b.capture('img-tableau-redim');
await b.ev(`(document.querySelector('.tb2').focus(), 1)`);
for (let k = 0; k < 4; k++) await o.annulerZ();
const a3 = await objet();
b.ok(a3 && a3.w === a0.w && a3.h === a0.h && a3.x === a0.x && a3.y === a0.y, '⌘Z × 4 → taille d’origine');
// rognage
r = await o.rect(sel); await b.clic([r.x + r.w / 2, r.y + r.h / 2], { att: 500 });
await b.clic(await b.pos(`document.querySelector('.mini-barre [data-option="rogner"]')`, false), { att: 600 });
b.ok(await o.rgnOuvert(), '« Rogner » (mini barre de l’image) ouvre le cadre de rognage');
await o.glisser(await o.rgnCoin('nw'), 50, 30);
await o.glisser(await o.rgnCoin('se'), -40, -20);
await b.capture('img-tableau-rognage');
await o.entree();
const a4 = await objet();
const F = (a) => (a.rognage ? { x: a.x - (a.rognage.x / a.rognage.w) * a.w, w: a.w / a.rognage.w, y: a.y - (a.rognage.y / a.rognage.h) * a.h } : { x: a.x, w: a.w, y: a.y });
b.ok(a4.rognage && a4.rognage.w < 1 && Math.abs(F(a4).x - a0.x) < 0.6 && Math.abs(F(a4).w - a0.w) < 1 && a4.blobId === a0.blobId, 'Entrée → rognage enregistré, image entière en place, même fichier', JSON.stringify(a4.rognage));
await b.capture('img-tableau-rognee');
r = await o.rect(sel); await b.clic([r.x + r.w / 2, r.y + r.h / 2], { att: 500 });
await b.clic(await b.pos(`document.querySelector('.mini-barre [data-option="rogner"]')`, false), { att: 600 });
await o.glisser(await o.rgnCoin('ne'), -30, 20);
await o.echap();
b.ok(JSON.stringify((await objet()).rognage) === JSON.stringify(a4.rognage), 'Échap → rien n’est écrit');
await b.clic(await b.pos(`document.querySelector('.mini-barre [data-option="rogner"]')`, false), { att: 600 });
await b.clic(await b.pos(`document.querySelector('.rgn [data-rgn="entiere"]')`, false), { att: 300 });
await o.entree();
const a6 = await objet();
b.ok(!a6.rognage && Math.abs(a6.w - a0.w) < 0.6 && Math.abs(a6.x - a0.x) < 0.6, '« Image entière » → rognage retiré (réversible)');
await b.ev(`(document.querySelector('.tb2').focus(), 1)`);
await o.annulerZ();
b.ok(JSON.stringify((await objet()).rognage) === JSON.stringify(a4.rognage), '⌘Z → le rognage revient');
await o.annulerZ();
b.ok(!(await objet()).rognage, '⌘Z → image entière');
b.ok(b.erreurs.length === 0, 'aucune erreur JS', b.erreurs.slice(0, 3).join(' | '));
process.exit(0);
